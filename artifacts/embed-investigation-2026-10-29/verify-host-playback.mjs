import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
const { chromium } = await import(pathToFileURL(process.argv[2]).href);
const out=path.dirname(fileURLToPath(import.meta.url));
const browser=await chromium.launch({channel:'msedge',headless:true});
const context=await browser.newContext({viewport:{width:1440,height:1000},locale:'zh-TW',serviceWorkers:'block'});
const page=await context.newPage();
const result={};
await page.goto('http://localhost:4174/#/song/MichiTeyuKu',{waitUntil:'domcontentloaded'});
await page.locator('iframe#yt-player').waitFor();
await page.waitForTimeout(2000);
result.before={state:await page.locator('#video-status').getAttribute('data-state'),message:await page.locator('#video-status-text').textContent()};
if(await page.locator('#video-start').isVisible())await page.locator('#video-start').click();
const frame=page.frames().find(f=>/youtube\.com\/embed\//.test(f.url()));
if(await frame.locator('.ytp-large-play-button').isVisible())await frame.locator('.ytp-large-play-button').click();
await page.waitForTimeout(4000);
result.after={state:await page.locator('#video-status').getAttribute('data-state'),media:await frame.locator('video').evaluateAll(v=>v.map(e=>({time:e.currentTime,duration:e.duration,paused:e.paused,readyState:e.readyState})))};
await page.screenshot({path:path.join(out,'localhost-playing.png'),animations:'disabled'});
await fs.writeFile(path.join(out,'localhost-playback.json'),JSON.stringify(result,null,2)+'\n');
console.log(JSON.stringify(result,null,2));
await browser.close();
