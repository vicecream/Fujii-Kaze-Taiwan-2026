import fs from "node:fs/promises";
import path from "node:path";
import { pathToFileURL } from "node:url";
import { SONG_LYRICS } from "../src/song-lyrics.js";
import { SONG_WORD_TIMING } from "../src/song-word-timing.js";
import { TIMING_FORMAT, validateReviewedTiming, sourceFingerprint } from "../src/karaoke-timing.js";
import { buildCatalog, fileHash, root } from "./word-timing-catalog.mjs";

const requireValue = (ok, message) => { if (!ok) throw new Error(message); };
export async function prepareWordImport(review, candidate, audioFile, previous){
  const song = SONG_LYRICS.find(item => item.id === review.songId);
  requireValue(song && review.format === "karaoke-review-v1", "Unknown song or review format");
  requireValue(candidate.format === "karaoke-candidate-v1", "Candidate file required");
  requireValue(candidate.songId === review.songId, "Review/candidate song mismatch");
  requireValue(candidate.models && Object.keys(candidate.models).length
    && candidate.versions && Object.keys(candidate.versions).length, "Candidate model/version provenance required");
  const sourceKeys = ["youtubeId", "sourceFingerprint", "lrcSha256", "audioSha256", "alignmentAudioSha256"];
  for (const key of sourceKeys) requireValue(review[key] === candidate[key], `Review/candidate ${key} changed`);
  requireValue(candidate.audioSha256 === await fileHash(audioFile), "Original audio file changed");
  const entry = (await buildCatalog()).songs.find(item => item.songId === song.id);
  requireValue(review.lrcSha256 === entry.lrcSha256 && review.sourceFingerprint === await sourceFingerprint(song), "Current lyric source changed; reconfirm source and lines");
  if (previous) for (const key of sourceKeys) requireValue(previous[key] === review[key], `Archived ${key} changed; archive old reviews before a new source import`);
  requireValue(Array.isArray(review.lines) && review.lines.length > 0, "Review contains no decisions");
  requireValue(new Set(review.lines.map(line => line.index)).size === review.lines.length, "Duplicate review occurrence");
  const merged = new Map((previous?.lines || []).map(line => [line.index, line]));
  for (const line of review.lines){
    requireValue(["pending", "passed", "needs-fix", "line-only"].includes(line.review?.status), "Unknown review state");
    const source = entry.lines[line.index];
    requireValue(source && line.lineId === source.lineId && line.text === source.text
      && line.textSha256 === source.textSha256 && line.sourceStart === source.sourceStart
      && (line.sourceEnd ?? null) === source.sourceEnd, "Review occurrence differs from current LRC");
    if (["needs-fix", "line-only"].includes(line.review.status))
      requireValue(typeof line.review.note === "string" && line.review.note.trim(), "Fallback exception needs a reason");
    requireValue(candidate.lines.some(item => item.index === line.index && item.lineId === line.lineId), "No matching candidate occurrence");
    merged.set(line.index, line);
  }
  const archive = { ...review, lines: [...merged.values()].sort((a, b) => a.index - b.index) };
  const data = {
    format: TIMING_FORMAT, songId: song.id,
    ...Object.fromEntries(sourceKeys.map(key => [key, review[key]])),
    duration: candidate.duration, sourceReview: review.sourceReview,
    models: candidate.models, versions: candidate.versions,
    lines: archive.lines.filter(line => line.review.status === "passed"),
  };
  await validateReviewedTiming(song, data);
  return { data, archive };
}

export async function importWordTiming(reviewFile, candidateFile, audioFile, { write = false, destination = root } = {}){
  const review = JSON.parse(await fs.readFile(reviewFile, "utf8"));
  const candidate = JSON.parse(await fs.readFile(candidateFile, "utf8"));
  requireValue(/^[A-Za-z0-9]+$/.test(review.songId || ""), "Invalid song ID");
  const archivePath = path.join(destination, "lyrics/word-timing/reviews", `${review.songId}.json`);
  let previous;
  try { previous = JSON.parse(await fs.readFile(archivePath, "utf8")); }
  catch (error) { if (error.code !== "ENOENT") throw error; }
  const { data, archive } = await prepareWordImport(review, candidate, audioFile, previous);
  if (write){
    await fs.mkdir(path.dirname(archivePath), { recursive: true });
    const timing = { ...SONG_WORD_TIMING, [data.songId]: data };
    const output = path.join(destination, "src/song-word-timing.js");
    await fs.writeFile(archivePath, JSON.stringify(archive, null, 2) + "\n");
    await fs.writeFile(output, "// Generated by scripts/import-word-timing.mjs. Only listened, passed lines belong here.\nexport const SONG_WORD_TIMING = " + JSON.stringify(timing, null, 2) + ";\n");
  }
  console.log(`${data.songId}: ${data.lines.length} listened, passed lines; ${archive.lines.length - data.lines.length} pending/line-only decisions. ${write ? "Imported." : "Preview only; add --write."}`);
  return { data, archive };
}

